"""Generate complete surahs starting in Juz 8 and 12–15, preserving existing Al-Kahf."""
import concurrent.futures
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("quran_generator", ROOT / "scripts/generate-quran-juz23-26.py")
generator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generator)

CHAPTERS = [
    (8, 7, "araf", "Al-A'raf", "الأعراف", 206),
    (12, 12, "yusuf", "Yusuf", "يوسف", 111),
    (13, 13, "rad", "Ar-Ra'd", "الرعد", 43),
    (13, 14, "ibrahim", "Ibrahim", "إبراهيم", 52),
    (14, 15, "hijr", "Al-Hijr", "الحجر", 99),
    (14, 16, "nahl", "An-Nahl", "النحل", 128),
    (15, 17, "isra", "Al-Isra", "الإسراء", 111),
]

if __name__ == "__main__":
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        data = list(pool.map(generator.fetch, CHAPTERS))
    for juz in [8, 12, 13, 14, 15]:
        suffix = "15b" if juz == 15 else str(juz)
        name = "juz15MoreSurahs" if juz == 15 else f"juz{juz}Surahs"
        out = '// Generated by scripts/generate-quran-juz8-12-15.py: complete surahs under their starting Juz.\n// Quran.com Uthmani text; Ahmad Al-Nufais/Tarteel verse audio.\nimport type { SurahData } from "./surahs";\n\n'
        out += f"export const {name}: readonly SurahData[] = " + json.dumps([s for j, s in data if j == juz], ensure_ascii=False, indent=2) + ";\n"
        (ROOT / f"src/data/surahsJuz{suffix}.ts").write_text(out)
    print("Generated", len(data), "complete surahs,", sum(len(s["verses"]) for _, s in data), "verses")