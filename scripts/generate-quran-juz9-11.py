"""Regenerate complete surahs starting in Juz 9–11 from Quran.com Uthmani text.
Audio: existing Ahmad Al-Nufais/Tarteel verse recordings. No invented word timings.
"""
import concurrent.futures
import json
from pathlib import Path
import requests

CHAPTERS = [
 (9,8,'anfal','Al-Anfal','الأنفال',75),(10,9,'tawbah','At-Tawbah','التوبة',129),(11,10,'yunus','Yunus','يونس',109),(11,11,'hud','Hud','هود',123),
]
OLD = [
 (23,37,'saffat','As-Saffat','الصافات',182),(23,38,'sad','Sad','ص',88),(23,39,'zumar','Az-Zumar','الزمر',75),
 (24,40,'ghafir','Ghafir','غافر',85),(24,41,'fussilat','Fussilat','فصلت',54),
 (25,42,'shura','Ash-Shura','الشورى',53),(25,43,'zukhruf','Az-Zukhruf','الزخرف',89),(25,44,'dukhan','Ad-Dukhan','الدخان',59),(25,45,'jathiyah','Al-Jathiyah','الجاثية',37),
 (26,46,'ahqaf','Al-Ahqaf','الأحقاف',35),(26,47,'muhammad','Muhammad','محمد',38),(26,48,'fath','Al-Fath','الفتح',29),(26,49,'hujurat','Al-Hujurat','الحجرات',18),(26,50,'qaf','Qaf','ق',45),(26,51,'dhariyat','Adh-Dhariyat','الذاريات',60),
]

def fetch(ch):
 juz,n,id,name,ar,count=ch
 r=requests.get(f'https://api.quran.com/api/v4/quran/verses/uthmani?chapter_number={n}',timeout=40); r.raise_for_status()
 verses=r.json()['verses']
 assert [v['verse_key'] for v in verses]==[f'{n}:{i}' for i in range(1,count+1)]
 return juz,dict(id=id,number=n,name=f'Surah {name}',arabicName=f'سورة {ar}',reciter='Ahmad Al-Nufais',tone=['sun','mint','sky','berry'][n%4],scene=['dawn','trees','flowers','foliage'][n%4],verses=[dict(arabic=v['text_uthmani'],audio=f'https://audio-cdn.tarteel.ai/quran/alnufais/{n:03d}{i:03d}.mp3') for i,v in enumerate(verses,1)])

if __name__=='__main__':
 with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool: data=list(pool.map(fetch,CHAPTERS))
 root=Path(__file__).resolve().parents[1]
 for juz in range(9,12):
  out='// Generated by scripts/generate-quran-juz9-11.py: complete surahs under their starting Juz.\n// Quran.com Uthmani text; Ahmad Al-Nufais, Tarteel recitation 42 verse audio.\nimport type { SurahData } from "./surahs";\n\n'
  out+=f'export const juz{juz}Surahs: readonly SurahData[] = '+json.dumps([s for j,s in data if j==juz],ensure_ascii=False,indent=2)+';\n'
  (root/f'src/data/surahsJuz{juz}.ts').write_text(out)
 print('Generated',len(data),'complete surahs,',sum(len(s['verses']) for _,s in data),'verses')
